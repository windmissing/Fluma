  schema: 'G12_READER_SCHEMA_V1',
  profile: m.profile,
  state: m.state, work: m.work, config: { materialConfig128: m.config.materialConfig128 },
  dispatch: { passCount: d.passCount, opcodes: d.opcodes },
  cold: { schema: m.cold.schema, page: m.cold.page, slots: m.cold.slots },
