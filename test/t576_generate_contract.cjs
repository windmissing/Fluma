g += `const uint G12_WORK_WET_DRIVE[4]=uint[4](${m.resources.map(r => Math.floor(r.workSegments[7].byteStart / 4) + 'u').join(',')});\n`;
g += `const uint G12_WORK_WATER_WIDE_COLUMN[4]=uint[4](${m.resources.map(r => Math.floor(r.workSegments[8].byteStart / 4) + 'u').join(',')});\n`;
g += `const uint G12_WORK_SIX_TRIAL_SUMMARY[4]=uint[4](${m.resources.map(r => Math.floor(r.workSegments[9].byteStart / 4) + 'u').join(',')});\n`;
